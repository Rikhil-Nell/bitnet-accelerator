#!/usr/bin/env python3
"""Draft table for speculative decoding on the board.

The board verifies one guessed token per pass over the weights (engine NB=2). Guesses
come from (1) the conversation itself: the most recent earlier occurrence of the last
two tokens, and (2) this table: for the last 3, 2 or 1 tokens, the continuation the
model itself produced most often in a corpus of its own answers (spec_corpus*.py).

A wrong guess never changes the output (the model's own prediction wins), it only
costs the A9 work of the extra position. Keys are 32-bit FNV-1a hashes of
(order, tokens): collisions only make a guess worse.

  python tools/bitnet/ngram_table.py            # evaluate + write fpga/ps/bitnet_zybo/ngram_table.h
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
CORPORA = [Path("D:/xilinx-tools/spec_corpus.npz"), Path("D:/xilinx-tools/spec_corpus2.npz")]
HELD = Path("D:/xilinx-tools/bitnet_head_states.npz")
OUT_H = ROOT / "fpga" / "ps" / "bitnet_zybo" / "ngram_table.h"
MAX_ORDER = 3


def fnv(order: int, toks) -> int:
    h = 0x811C9DC5 ^ order
    for t in toks:
        for sh in (0, 8, 16):
            h ^= (t >> sh) & 0xFF
            h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def load(path: Path) -> list[list[int]]:
    d = np.load(path)
    ids, out, o = d["ids"].tolist(), [], 0
    for L in d["lens"].tolist():
        out.append(ids[o : o + L])
        o += L
    return out


def build(seqs, min_count: int, min_frac: float) -> dict[int, int]:
    counts = defaultdict(lambda: defaultdict(int))
    for s in seqs:
        for i in range(1, len(s)):
            for n in range(1, MAX_ORDER + 1):
                if i - n >= 0:
                    counts[(n, tuple(s[i - n : i]))][s[i]] += 1
    table: dict[int, int] = {}
    for (n, ctx), nxt in counts.items():
        tok, c = max(nxt.items(), key=lambda kv: kv[1])
        if c >= min_count and c >= min_frac * sum(nxt.values()):
            table[fnv(n, ctx)] = tok
    return table


def lookup2(ctx: list[int]) -> int | None:
    """most recent earlier occurrence of the last two tokens -> the token after it"""
    if len(ctx) < 3:
        return None
    a, b = ctx[-2], ctx[-1]
    for i in range(len(ctx) - 3, -1, -1):
        if ctx[i] == a and ctx[i + 1] == b:
            return ctx[i + 2]
    return None


def draft(ctx: list[int], table: dict[int, int]) -> int | None:
    d = lookup2(ctx)
    if d is not None:
        return d
    for n in range(MAX_ORDER, 0, -1):
        if len(ctx) >= n:
            t = table.get(fnv(n, ctx[-n:]))
            if t is not None:
                return t
    return None


def simulate(runs, table, pl_ms: float, a9_ms: float, extra_ms: float):
    """B = 2: each pass yields 1 token, +1 if the draft was right. Returns
    (tokens per pass, fraction of passes with a draft, estimated ms per token)."""
    toks = passes = drafted = 0
    t_ms = 0.0
    for prompt, out in runs:
        i = 0
        while i < len(out) - 1:
            d = draft(prompt + out[: i + 1], table)
            ok = d is not None and i + 2 < len(out) and d == out[i + 1]
            passes += 1
            drafted += d is not None
            t_ms += pl_ms + a9_ms + (extra_ms if d is not None else 0.0)
            i += 2 if ok else 1
            toks += 2 if ok else 1
    return toks / passes, drafted / passes, t_ms / toks


def write_header(table: dict[int, int]) -> None:
    keys = sorted(table)
    L = ["/* GENERATED by tools/bitnet/ngram_table.py: draft table for speculative decoding.",
         " * Sorted 32-bit FNV-1a keys of (order, last tokens) -> most frequent next token. */",
         "#ifndef NGRAM_TABLE_H", "#define NGRAM_TABLE_H", "#include <stdint.h>",
         f"#define NGRAM_N {len(keys)}", f"#define NGRAM_MAX_ORDER {MAX_ORDER}",
         "static const uint32_t ngram_keys[NGRAM_N] = {"]
    for i in range(0, len(keys), 12):
        L.append("    " + ",".join(f"0x{k:08x}u" for k in keys[i : i + 12]) + ",")
    L += ["};", "static const uint32_t ngram_vals[NGRAM_N] = {"]
    for i in range(0, len(keys), 16):
        L.append("    " + ",".join(str(table[k]) for k in keys[i : i + 16]) + ",")
    L += ["};", "#endif", ""]
    OUT_H.write_text("\n".join(L), encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pl-ms", type=float, default=121.0, help="engine time per pass")
    ap.add_argument("--a9-ms", type=float, default=15.0, help="serial A9 time per position")
    ap.add_argument("--extra-ms", type=float, default=15.0, help="A9 time of the second position")
    args = ap.parse_args()
    from eval_spec import load_runs
    runs = load_runs(HELD)
    seqs = [s for p in CORPORA if p.exists() for s in load(p)]
    print(f"corpus: {len(seqs)} sequences, {sum(map(len, seqs))} tokens; held-out: {len(runs)} answers")
    base = args.pl_ms + args.a9_ms
    print(f"no speculation: {base:.0f} ms/token = {1000 / base:.2f} tok/s")
    best = None
    for mc in (1, 2, 3):
        for mf in (0.0, 0.3, 0.5, 0.7):
            t = build(seqs, mc, mf)
            tpp, frac, ms = simulate(runs, t, args.pl_ms, args.a9_ms, args.extra_ms)
            print(f"min_count {mc} min_frac {mf:.1f}: {len(t):6d} entries, {tpp:.3f} tok/pass, "
                  f"drafts in {frac * 100:3.0f}% of passes -> {ms:.0f} ms/token = {1000 / ms:.2f} tok/s")
            if best is None or ms < best[0]:
                best = (ms, mc, mf, t)
    ms, mc, mf, t = best
    write_header(t)
    print(f"wrote {OUT_H.relative_to(ROOT)}: min_count {mc}, min_frac {mf}, {len(t)} entries "
          f"({len(t) * 8 / 1e6:.1f} MB), est. {1000 / ms:.2f} tok/s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
