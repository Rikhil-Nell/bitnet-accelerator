#!/usr/bin/env python3
"""Generate C weight/norm tables for bitlinear_server from bitnet_weights.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJ = ("attn_q", "attn_k", "attn_v", "attn_output", "ffn_gate", "ffn_up", "ffn_down")
NORM = ("attn_norm", "attn_sub_norm", "ffn_norm", "ffn_sub_norm")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, default=Path("D:/xilinx-tools/bitnet_weights.json"))
    ap.add_argument("--out", type=Path, default=Path("fpga/ps/bitlinear_server/weight_manifest.h"))
    args = ap.parse_args()
    man = json.loads(args.manifest.read_text(encoding="utf-8"))
    mats = man["matrices"]
    norms = man.get("norms", {})
    n_layer = max(int(k.split(".")[0]) for k in mats) + 1

    lines = [
        "/* Auto-generated by tools/bitnet/gen_ps_manifest.py — do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct { uint32_t addr; uint16_t n, k; } WDesc;",
        "typedef struct {",
        "    WDesc attn_q, attn_k, attn_v, attn_output, ffn_gate, ffn_up, ffn_down;",
        "} LayerWeights;",
        "",
        f"#define BITNET_N_LAYER {n_layer}",
        "",
        "static const LayerWeights LAYER_WEIGHTS[BITNET_N_LAYER] = {",
    ]
    for i in range(n_layer):
        row = []
        for p in PROJ:
            e = mats[f"{i}.{p}"]
            row.append(f"{{0x{e['addr']:08X}U, {e['n']}U, {e['k']}U}}")
        lines.append("    {" + ", ".join(row) + "},")
    lines.append("};")
    lines.append("")

    if norms:
        lines += [
            "typedef struct {",
            "    uint32_t attn_norm, attn_sub_norm, ffn_norm, ffn_sub_norm;",
            "} LayerNorms;",
            "",
            "static const LayerNorms LAYER_NORMS[BITNET_N_LAYER] = {",
        ]
        for i in range(n_layer):
            row = [f"0x{norms[f'{i}.{n}']['addr']:08X}U" for n in NORM]
            lines.append("    {" + ", ".join(row) + "},")
        lines.append("};")
        lines.append("#define BITNET_HAS_NORMS 1")
    else:
        lines.append("#define BITNET_HAS_NORMS 0")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out} ({n_layer} layers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
