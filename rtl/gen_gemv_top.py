#!/usr/bin/env python3
"""Generate rtl/gemv_top.v: AXI-Lite CSRs + NU gemv_units, one AXI3 master per HP port.

The port list is long and repetitive (and needs Vivado interface attributes so the
block design sees proper AXI3 / AXI-Lite interfaces), so it is generated.
Run: python rtl/gen_gemv_top.py
"""

from pathlib import Path

NU = 4  # STATUS packs per-unit bits into [11:4]; change it if NU changes
VERSION = 0x47454D33  # "GEM3": GEM2 + optional batch of two activation vectors (NB, 0x54)

# (name, direction from master's view, width) for an AXI3 master to a Zynq HP port
AXI3 = [
    ("araddr", "out", 32), ("arlen", "out", 4), ("arsize", "out", 3), ("arburst", "out", 2),
    ("arlock", "out", 2), ("arcache", "out", 4), ("arprot", "out", 3), ("arqos", "out", 4),
    ("arid", "out", 6), ("arvalid", "out", 1), ("arready", "in", 1),
    ("rdata", "in", 64), ("rresp", "in", 2), ("rlast", "in", 1), ("rid", "in", 6),
    ("rvalid", "in", 1), ("rready", "out", 1),
    ("awaddr", "out", 32), ("awlen", "out", 4), ("awsize", "out", 3), ("awburst", "out", 2),
    ("awlock", "out", 2), ("awcache", "out", 4), ("awprot", "out", 3), ("awqos", "out", 4),
    ("awid", "out", 6), ("awvalid", "out", 1), ("awready", "in", 1),
    ("wdata", "out", 64), ("wstrb", "out", 8), ("wlast", "out", 1), ("wid", "out", 6),
    ("wvalid", "out", 1), ("wready", "in", 1),
    ("bresp", "in", 2), ("bid", "in", 6), ("bvalid", "in", 1), ("bready", "out", 1),
]
LITE = [
    ("awaddr", "in", 12), ("awprot", "in", 3), ("awvalid", "in", 1), ("awready", "out", 1),
    ("wdata", "in", 32), ("wstrb", "in", 4), ("wvalid", "in", 1), ("wready", "out", 1),
    ("bresp", "out", 2), ("bvalid", "out", 1), ("bready", "in", 1),
    ("araddr", "in", 12), ("arprot", "in", 3), ("arvalid", "in", 1), ("arready", "out", 1),
    ("rdata", "out", 32), ("rresp", "out", 2), ("rvalid", "out", 1), ("rready", "in", 1),
]


def port(prefix, iface, sig, d, w, params=None):
    rng = f"[{w-1}:0] " if w > 1 else ""
    out = []
    if params:
        out.append(f'    (* X_INTERFACE_PARAMETER = "{params}" *)')
    out.append(f'    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm_rtl:1.0 {iface} {sig.upper()}" *)')
    out.append(f"    {'output' if d == 'out' else 'input '} wire {rng}{prefix}_{sig}")
    return out


def main() -> None:
    busifs = ":".join(["S_AXI"] + [f"M{u}_AXI" for u in range(NU)])
    L = [
        "`timescale 1ns/1ps",
        "// GENERATED by rtl/gen_gemv_top.py -- edit the generator, not this file.",
        "//",
        f"// gemv_top: AXI-Lite CSRs + {NU} gemv_units, each on its own AXI3 HP port.",
        "// Register map: docs/ARCHITECTURE.md.",
        "module gemv_top (",
        f'    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF {busifs}, ASSOCIATED_RESET aresetn" *)',
        '    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 aclk CLK" *)',
        "    input  wire aclk,",
        '    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)',
        '    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 aresetn RST" *)',
        "    input  wire aresetn,",
    ]
    ports = []
    for i, (sig, d, w) in enumerate(LITE):
        params = "PROTOCOL AXI4LITE, DATA_WIDTH 32, ADDR_WIDTH 12" if i == 0 else None
        ports.append(port("s_axi", "S_AXI", sig, d, w, params))
    for u in range(NU):
        for i, (sig, d, w) in enumerate(AXI3):
            params = ("PROTOCOL AXI3, DATA_WIDTH 64, ADDR_WIDTH 32, ID_WIDTH 6, "
                      "MAX_BURST_LENGTH 16, NUM_READ_OUTSTANDING 8, NUM_WRITE_OUTSTANDING 8, "
                      "SUPPORTS_NARROW_BURST 0") if i == 0 else None
            ports.append(port(f"m{u}_axi", f"M{u}_AXI", sig, d, w, params))
    for n, p in enumerate(ports):
        if n < len(ports) - 1:
            p[-1] += ","
        L += p
    L.append(");")
    L.append("")

    L.append(f"""    localparam NU = {NU};

    // ---------------- CSRs ----------------
    reg        start;
    reg        mode;
    reg        nb2;
    reg [10:0] x_beats;
    reg [12:0] row_beats;
    reg [15:0] rows;
    reg [31:0] x_addr;
    reg [31:0] w_addr [0:NU-1];
    reg [31:0] y_addr [0:NU-1];
    reg [31:0] cycles;
    reg        counting;

    wire [NU-1:0] u_done, u_busy, u_err;
    wire [15:0] u_prog [0:NU-1];
    reg rst_n;
    always @(posedge aclk) rst_n <= aresetn;
    wire all_done = &u_done && !start;

    reg awready_r, wready_r, bvalid_r, arready_r, rvalid_r;
    reg [31:0] rdata_r;
    assign s_axi_awready = awready_r;
    assign s_axi_wready  = wready_r;
    assign s_axi_bvalid  = bvalid_r;
    assign s_axi_bresp   = 2'b00;
    assign s_axi_arready = arready_r;
    assign s_axi_rvalid  = rvalid_r;
    assign s_axi_rdata   = rdata_r;
    assign s_axi_rresp   = 2'b00;

    wire wr_go = s_axi_awvalid && s_axi_wvalid && !bvalid_r && !awready_r;
    wire rd_go = s_axi_arvalid && !rvalid_r && !arready_r;

    integer n;
    always @(posedge aclk) begin
        if (!rst_n) begin
            awready_r <= 1'b0; wready_r <= 1'b0; bvalid_r <= 1'b0;
            arready_r <= 1'b0; rvalid_r <= 1'b0; rdata_r  <= 32'd0;
            start <= 1'b0; mode <= 1'b0; nb2 <= 1'b0; x_beats <= 11'd0; row_beats <= 13'd0; rows <= 16'd0; x_addr <= 32'd0;
            cycles <= 32'd0; counting <= 1'b0;
            for (n = 0; n < NU; n = n + 1) begin
                w_addr[n] <= 32'd0;
                y_addr[n] <= 32'd0;
            end
        end else begin
            start     <= 1'b0;
            awready_r <= 1'b0;
            wready_r  <= 1'b0;
            arready_r <= 1'b0;

            if (wr_go) begin
                awready_r <= 1'b1;
                wready_r  <= 1'b1;
                bvalid_r  <= 1'b1;
                case (s_axi_awaddr[7:0])
                    8'h00: start  <= s_axi_wdata[0] && !(|u_busy);
                    8'h08: mode   <= s_axi_wdata[0];
                    8'h0C: x_beats <= s_axi_wdata[10:0];
                    8'h50: row_beats <= s_axi_wdata[12:0];
                    8'h54: nb2 <= s_axi_wdata[0];
                    8'h10: rows   <= s_axi_wdata[15:0];
                    8'h14: x_addr <= s_axi_wdata;
                    default: begin
                        for (n = 0; n < NU; n = n + 1) begin
                            if (s_axi_awaddr[7:0] == 8'h20 + 8*n) w_addr[n] <= s_axi_wdata;
                            if (s_axi_awaddr[7:0] == 8'h24 + 8*n) y_addr[n] <= s_axi_wdata;
                        end
                    end
                endcase
            end
            if (bvalid_r && s_axi_bready) bvalid_r <= 1'b0;

            if (rd_go) begin
                arready_r <= 1'b1;
                rvalid_r  <= 1'b1;
                case (s_axi_araddr[7:0])
                    8'h04: rdata_r <= {{20'd0, u_err, u_done, 1'b0, |u_err, |u_busy, all_done}};
                    8'h08: rdata_r <= {{31'd0, mode}};
                    8'h0C: rdata_r <= {{21'd0, x_beats}};
                    8'h50: rdata_r <= {{19'd0, row_beats}};
                    8'h54: rdata_r <= {{31'd0, nb2}};
                    8'h10: rdata_r <= {{16'd0, rows}};
                    8'h14: rdata_r <= x_addr;
                    8'h18: rdata_r <= cycles;
                    8'h1C: rdata_r <= 32'h{VERSION:08X};
                    default: begin
                        rdata_r <= 32'd0;
                        for (n = 0; n < NU; n = n + 1) begin
                            if (s_axi_araddr[7:0] == 8'h20 + 8*n) rdata_r <= w_addr[n];
                            if (s_axi_araddr[7:0] == 8'h24 + 8*n) rdata_r <= y_addr[n];
                            if (s_axi_araddr[7:0] == 8'h40 + 4*n) rdata_r <= {{16'd0, u_prog[n]}};
                        end
                    end
                endcase
            end
            if (rvalid_r && s_axi_rready) rvalid_r <= 1'b0;

            // perf counter: clocks from start until every unit is done
            if (start) begin
                cycles   <= 32'd0;
                counting <= 1'b1;
            end else if (counting) begin
                if (&u_done) counting <= 1'b0;
                else         cycles   <= cycles + 1'b1;
            end
        end
    end
""")

    for u in range(NU):
        p = f"m{u}_axi"
        L.append(f"""    // ---------------- unit {u} ----------------
    assign {p}_arsize  = 3'b011;
    assign {p}_arburst = 2'b01;
    assign {p}_arlock  = 2'b00;
    assign {p}_arcache = 4'b0011;
    assign {p}_arprot  = 3'b000;
    assign {p}_arqos   = 4'd0;
    assign {p}_arid    = 6'd0;
    assign {p}_awsize  = 3'b011;
    assign {p}_awburst = 2'b01;
    assign {p}_awlock  = 2'b00;
    assign {p}_awcache = 4'b0011;
    assign {p}_awprot  = 3'b000;
    assign {p}_awqos   = 4'd0;
    assign {p}_awid    = 6'd0;
    assign {p}_wid     = 6'd0;
    assign {p}_wstrb   = 8'hFF;

    gemv_unit u{u} (
        .clk(aclk), .rstn(aresetn),
        .start(start), .mode(mode), .nb2(nb2), .x_beats(x_beats), .row_beats(row_beats), .rows(rows),
        .x_addr(x_addr), .w_addr(w_addr[{u}]), .y_addr(y_addr[{u}]),
        .done(u_done[{u}]), .busy(u_busy[{u}]), .err(u_err[{u}]), .progress(u_prog[{u}]),
        .araddr({p}_araddr), .arlen({p}_arlen), .arvalid({p}_arvalid), .arready({p}_arready),
        .rdata({p}_rdata), .rvalid({p}_rvalid), .rlast({p}_rlast), .rresp({p}_rresp), .rready({p}_rready),
        .awaddr({p}_awaddr), .awlen({p}_awlen), .awvalid({p}_awvalid), .awready({p}_awready),
        .wdata({p}_wdata), .wlast({p}_wlast), .wvalid({p}_wvalid), .wready({p}_wready),
        .bresp({p}_bresp), .bvalid({p}_bvalid), .bready({p}_bready)
    );
""")
    L.append("endmodule")
    out = Path(__file__).with_name("gemv_top.v")
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
