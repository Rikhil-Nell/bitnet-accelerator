#!/usr/bin/env python3
"""Generate rtl/t5_decode.v: one byte holding 5 ternary weights -> 5 x 2-bit codes.

Packing ("T5", 1.6 bits per weight): byte = sum_i (t_i + 1) * 3^i, i = 0..4, t_i in
{-1, 0, +1}; 3^5 = 243 <= 256. Output code per weight, as the 2-bit format:
00 = 0, 01 = +1, 11 = -1; weight i in bits [2i+1:2i]. Bytes >= 243 never occur and
decode to zeros. Run: python rtl/gen_t5_decode.py
"""
from pathlib import Path

CODE = {-1: 0b11, 0: 0b00, 1: 0b01}


def decode(b: int) -> int:
    if b >= 243:
        return 0
    out = 0
    for i in range(5):
        t = b % 3 - 1
        b //= 3
        out |= CODE[t] << (2 * i)
    return out


def main() -> None:
    L = [
        "`timescale 1ns/1ps",
        "// GENERATED by rtl/gen_t5_decode.py -- edit the generator, not this file.",
        "// One T5 byte (5 ternary weights, base 3) -> five 2-bit codes (00=0, 01=+1, 11=-1).",
        "module t5_decode (",
        "    input  wire [7:0] b,",
        "    output reg  [9:0] c",
        ");",
        "    always @(*) begin",
        "        case (b)",
    ]
    for b in range(243):
        L.append(f"            8'd{b}: c = 10'b{decode(b):010b};")
    L += ["            default: c = 10'b0;", "        endcase", "    end", "endmodule", ""]
    Path(__file__).with_name("t5_decode.v").write_text("\n".join(L), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
